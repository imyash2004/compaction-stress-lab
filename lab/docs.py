def fence(text: str, lang: str = "text") -> str:
    """A fenced block that survives backticks inside the text (issue texts often contain ``` blocks)."""
    longest = max((len(m) for m in __import__("re").findall(r"`+", text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{lang}\n{text.rstrip()}\n{ticks}"


def table(head: list[str], rows: list[list[str]]) -> str:
    esc = lambda c: str(c).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows])


def short(s: str, n: int) -> str:
    return s if len(s) <= n else s[:n] + "…"


def jsonl(p):
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


